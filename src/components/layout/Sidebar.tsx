type IconName = 'dashboard' | 'analytics' | 'threat' | 'clickForensics' | 'scheduledReports' | 'aiRules' | 'exclusions' | 'blacklist' | 'authorizations' | 'adAccounts';

function getNavIcon(icon: IconName) {
  const iconClass = 'w-6 h-6';
  switch (icon) {
    case 'dashboard':
      return <DashboardIcon className={iconClass} />;
    case 'analytics':
      return <AnalyticsIcon className={iconClass} />;
    case 'threat':
      return <ThreatIcon className={iconClass} />;
    case 'clickForensics':
      return <ClickForensicsIcon className={iconClass} />;
    case 'scheduledReports':
      return <ScheduledReportsIcon className={iconClass} />;
    case 'aiRules':
      return <AIRulesIcon className={iconClass} />;
    case 'exclusions':
      return <ExclusionsIcon className={iconClass} />;
    case 'blacklist':
      return <BlacklistIcon className={iconClass} />;
    case 'authorizations':
      return <AuthorizationsIcon className={iconClass} />;
    case 'adAccounts':
      return <AdAccountsIcon className={iconClass} />;
    default:
      return null;
  }
}

/**
 * Main sidebar navigation - Professional design with sections
 */
export function Sidebar({
  isCollapsed = false,
  onToggleCollapse,
  className,
}: SidebarProps) {
  const pathname = usePathname();

  return (
    <aside
      className={cn(
        'bg-white fixed h-screen flex flex-col transition-all duration-300 border-r border-gray-100',
        isCollapsed ? 'w-20' : 'w-[280px]',
        className
      )}
    >
      <div className="flex flex-col h-full">
        {/* Logo Header */}
        <div className="flex items-center justify-between px-6 pt-8 pb-8">
          {!isCollapsed && <ClickGuardLogo />}
          {isCollapsed && <ClickGuardLogoIcon />}
          {!isCollapsed && (
            <button
              onClick={onToggleCollapse}
              className="p-1.5 hover:bg-gray-100 rounded-lg transition-colors text-gray-400"
              aria-label="Collapse sidebar"
            >
              <CollapseIcon />
            </button>
          )}
        </div>

        {/* Navigation Sections */}
        <nav className="flex-1 px-4 overflow-y-auto">
          {navSections.map((section, sectionIndex) => (
            <div key={section.title} className={cn(sectionIndex > 0 && 'mt-6')}>
              {/* Section Title */}
              {!isCollapsed && (
                <h3 className="px-3 mb-3 text-xs font-semibold text-gray-400 tracking-wider">
                  {section.title}
                </h3>
              )}

              {/* Section Items */}
              <div className="flex flex-col gap-1">
                {section.items.map((item) => {
                  const isActive = item.href === '/'
                    ? pathname === '/'
                    : pathname.startsWith(item.href);

                  return (
                    <Link
                      key={item.href}
                      href={item.href}
                      className={cn(
                        'flex items-center gap-3 px-3 py-3 rounded-xl transition-all duration-200',
                        isActive
                          ? 'bg-[#e8e6ff] text-[#111553]'
                          : 'text-[#4a4a4a] hover:bg-gray-50',
                        isCollapsed && 'justify-center px-2'
                      )}
                    >
                      <span className={cn(
                        'flex-shrink-0',
                        isActive ? 'text-[#5E54FD]' : 'text-[#6b6b6b]'
                      )}>
                        {getNavIcon(item.icon as IconName)}
                      </span>
                      {!isCollapsed && (
                        <span className={cn(
                          'text-base font-medium',
                          isActive ? 'text-[#111553]' : 'text-[#4a4a4a]'
                        )}>
                          {item.label}
                        </span>
                      )}
                    </Link>
                  );
                })}
              </div>
            </div>
          ))}
        </nav>

        {/* Bottom Spacer */}
        <div className="pb-6" />
      </div>
    </aside>
  );
}

